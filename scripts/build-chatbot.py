"""Generate browser-safe scripted replies from the approved workspace Markdown.
Run from any directory: python scripts/build-chatbot.py
Only quoted customer-facing passages are included, never internal notes/database.
"""
from pathlib import Path
import hashlib
import json
import re

from workspace_paths import CONTENT

root = Path(__file__).resolve().parents[1]
source = (CONTENT / 'sales_script.md').read_text(encoding='utf-8')

def quotes(text):
    return re.findall(r'^> (.+)$', text, re.M)

sections = re.split(r'^## \d\. .+$', source, flags=re.M)[1:]
assert len(sections) == 4, 'Expected four sections in sales_script.md'
faq_parts = re.split(r'^### (\d{2})\. [“"](.+?)[”"]\s*$', sections[1], flags=re.M)
faqs = []
for i in range(1, len(faq_parts), 3):
    faqs.append({'id': int(faq_parts[i]), 'question': faq_parts[i+1], 'answers': quotes(faq_parts[i+2])})
assert len(faqs) == 10
assert [len(f['answers']) for f in faqs] == [2, 2, 3, 2, 1, 1, 2, 1, 2, 3], 'Script changed: review reply mapping'
later = quotes(sections[3])
assert len(later) == 3, 'Expected three replies in section 4 (Zalo hand-off)'
data = {'greeting': quotes(sections[0])[0], 'discovery': quotes(sections[0])[2],
        'faqs': faqs, 'later': later[0], 'decline': later[2]}
payload = json.dumps(data, ensure_ascii=False)
assert '{{' not in payload and 'Nội bộ:' not in payload
runtime = (root / 'chatbot-ui.js').read_text(encoding='utf-8')
assert runtime.count('/* SALES_SCRIPT_DATA */') == 1
generated = '// Generated by scripts/build-chatbot.py from sales_script.md; edit source, then rebuild.\n' + runtime.replace('/* SALES_SCRIPT_DATA */', payload)
(root / 'chatbot.js').write_text(generated, encoding='utf-8')
version = hashlib.sha256((generated + (root / 'chatbot.css').read_text(encoding='utf-8')).encode()).hexdigest()[:12]
pages = []
for page in root.rglob('*.html'):
    if any(part in ('outputs', '.git', 'node_modules') for part in page.relative_to(root).parts):
        continue
    html = page.read_text(encoding='utf-8')
    match = re.search(r'<script[^>]+src="([^"]*?)site\.min\.js[^"\s]*"[^>]*></script>', html)
    if not match:
        continue
    prefix = match.group(1)
    html = re.sub(r'\s*<link rel="stylesheet" href="[^"]*chatbot\.css[^\"]*"\s*/?>', '', html)
    html = re.sub(r'\s*<script defer src="[^"]*chatbot\.js[^\"]*"></script>', '', html)
    insert = f'\n    <link rel="stylesheet" href="{prefix}chatbot.css?v={version}" />\n    <script defer src="{prefix}chatbot.js?v={version}"></script>'
    html = re.sub(r'\s*</head>', insert + '\n  </head>', html)
    page.write_text(html, encoding='utf-8')
    pages.append(str(page.relative_to(root)))
print(json.dumps({'faq_count': len(faqs), 'pages': pages, 'version': version}, ensure_ascii=False))
